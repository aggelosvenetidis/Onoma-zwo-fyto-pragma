// =====================================================================
// normalize.js — Κανονικοποίηση ελληνικών λέξεων.
// "  Άρης!! " -> "ΑΡΗΣ",  "Ευαγγελία" -> "ΕΥΑΓΓΕΛΙΑ",  "ψάρι" -> "ΨΑΡΙ"
// =====================================================================

// Λατινικοί χαρακτήρες που μοιάζουν με ελληνικούς (π.χ. αν κάποιος γράψει "A" λατινικό).
const LATIN_LOOKALIKE = {
  A: 'Α', B: 'Β', E: 'Ε', Z: 'Ζ', H: 'Η', I: 'Ι', K: 'Κ', M: 'Μ',
  N: 'Ν', O: 'Ο', P: 'Ρ', T: 'Τ', Y: 'Υ', X: 'Χ',
};

/**
 * Επιστρέφει κεφαλαία, χωρίς τόνους/διαλυτικά, χωρίς σύμβολα,
 * με ένα κενό μεταξύ λέξεων (για π.χ. "Νέα Υόρκη").
 */
function normalize(input) {
  if (typeof input !== 'string') return '';
  let s = input
    .normalize('NFD')                 // χωρίζει γράμμα + τόνο
    .replace(/[̀-ͯ]/g, '')  // αφαιρεί τόνους & διαλυτικά
    .toUpperCase()
    .replace(/ς/g, 'Σ');              // τελικό σίγμα (για σιγουριά)

  s = s.replace(/[A-Z]/g, (c) => LATIN_LOOKALIKE[c] || c);
  // Κρατάμε μόνο ελληνικά κεφαλαία, κενά και παύλες (π.χ. "Πόρτο-Ρίκο")
  s = s.replace(/[^Α-Ω\s-]/g, '');
  s = s.replace(/-/g, ' ').replace(/\s+/g, ' ').trim();
  return s;
}

/** Καθαρίζει αυτό που θα εμφανιστεί σε άλλους (όχι για σύγκριση). */
function sanitizeDisplay(input, max) {
  if (typeof input !== 'string') return '';
  return input
    .replace(/[<>"'`\\]/g, '')
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, max);
}

module.exports = { normalize, sanitizeDisplay };
